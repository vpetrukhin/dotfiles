# Конфигурация плагина herdr-automatic-rename.
# Линкуется в ~/.config/herdr-automatic-rename/config.sh (см. links.prop).
# Файл подключается до naming.sh, поэтому всё заданное здесь перекрывает дефолты.
# Полный список настроек с пояснениями — в config.example.sh внутри каталога плагина:
# ~/.config/herdr/plugins/github/herdr-automatic-rename-*/config.example.sh

# ---- нумерация ----

# Без префиксов "[N] " у вкладок, воркспейсов и агентов.
# Три отдельных ключа заданы намеренно: конфиг с одним AUTO_INDEX=0 не запускает
# уборку уже проставленных префиксов у воркспейсов и агентов, а явное указание
# типа — запускает. Побочный эффект: уборка не отличает свои префиксы от чужих,
# поэтому имя, набранное руками как "[1] incident", тоже потеряет скобку.
AUTO_INDEX=0
AUTO_INDEX_WORKSPACES=0
AUTO_INDEX_TABS=0
AUTO_INDEX_AGENTS=0

# ---- иконки ----

# В ghostty стоит MesloLGS Nerd Font Mono, глифы рисуются корректно.
ICONS_ENABLED=1
ICON_STYLE=name_and_icon

# Пустая строка выключает запасной глиф: программы, которых нет во встроенной
# карте (~170 штук), остаются без иконки вместо «?», который всё равно ничего
# не сообщает.
ICON_FALLBACK=''

# Переопределения поверх встроенной карты.
ICON_MAP=(
  "claude=󰚩"
  "lazygit=󰊢"
)
